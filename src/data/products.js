/**
 * Get a single product by its slug.
 * @param {string} slug - The product slug to look up.
 * @returns {object|undefined} The product object, or undefined if not found.
 */
export function getProductBySlug(slug) {
  return products.find((product) => product.slug === slug);
}

/**
 * Get all products belonging to a category by its slug.
 * @param {string} categorySlug - The category slug to filter by.
 * @returns {object[]} Array of product objects in that category.
 */
export function getProductsByCategory(categorySlug) {
  const category = categories.find((cat) => cat.slug === categorySlug);
  if (!category) return [];
  return products.filter((product) => product.categoryId === category.id);
}
